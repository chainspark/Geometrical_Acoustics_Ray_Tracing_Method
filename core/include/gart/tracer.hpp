// Geometrical Acoustics Ray Tracing (gart) - image-source ray tracer for a shoe-box room.
//
// Each ray starts at the source with gain 1. Before every reflection it is tested
// against all receivers; on reflection the ray origin is mirrored across the wall hit
// (giving the image source), the direction is mirrored, and the gain is multiplied by
// the wall's complex reflection coefficient. The phase uses the full image-source
// distance, so interference between direct and reflected sound is captured.
#pragma once

#include <cstdint>
#include <limits>
#include <vector>

#include "gart/receivers.hpp"
#include "gart/rng.hpp"
#include "gart/scene.hpp"

namespace gart {

struct WallHit {
    double t;  // distance along the ray to the wall
    int axis;  // 0 = x, 1 = y, 2 = z
    int wall;  // Wall index
};

/// Wall where the line origin + t*dir leaves the room. The line must pass through
/// the room (true for the source and every image source generated by `trace`).
[[nodiscard]] inline WallHit exitWall(const Room& room, const Vec3& origin, const Vec3& dir) {
    const Vec3 size = room.size();
    WallHit best{std::numeric_limits<double>::infinity(), 0, Room::wallFor(0, true)};
    for (int a = 0; a < 3; ++a) {
        const double d = dir[a];
        if (d == 0.0) continue;
        const double t = d > 0 ? (size[a] - origin[a]) / d : -origin[a] / d;
        if (t < best.t) best = {t, a, Room::wallFor(a, d > 0)};
    }
    return best;
}

/// Mirrors the segment across the wall it hits: new image source, direction and gain.
inline void reflect(const Room& room, const WallHit& hit, Segment& s) {
    const int a = hit.axis;
    const double bound = s.dir[a] > 0 ? room.size()[a] : 0.0;
    s.origin[a] = 2.0 * bound - s.origin[a];
    s.dir[a] = -s.dir[a];
    s.gain *= room.R[static_cast<std::size_t>(hit.wall)];
}

/// Traces rays [begin, end) of the scene and adds their pressure to `acc`.
/// Receivers is PointReceivers or GridReceivers (anything with collect()).
template <class Receivers>
void trace(const Scene& scene, const Receivers& receivers, std::uint64_t begin, std::uint64_t end, Accumulator& acc) {
    const HitModel model(scene, receivers.radius);
    const int maxOrder = scene.settings.maxOrder;
    const double threshold = scene.settings.threshold;
    for (std::uint64_t i = begin; i < end; ++i) {
        Segment s{scene.source.position, rayDirection(scene.settings.seed, i), Complex{1.0, 0.0}};
        for (int order = 0; order <= maxOrder; ++order) {
            if (std::abs(s.gain) <= threshold) break; // absorbed
            receivers.collect(s, model, acc);
            if (order == maxOrder) break;
            reflect(scene.room, exitWall(scene.room, s.origin, s.dir), s);
        }
    }
}

/// Physical path of ray `index` for visualisation: the source followed by each wall hit,
/// up to maxOrder + 1 segments or until the ray is absorbed.
[[nodiscard]] inline std::vector<Vec3> rayPath(const Scene& scene, std::uint64_t index) {
    std::vector<Vec3> pts{scene.source.position};
    Segment s{scene.source.position, rayDirection(scene.settings.seed, index), Complex{1.0, 0.0}};
    for (int order = 0; order <= scene.settings.maxOrder; ++order) {
        if (std::abs(s.gain) <= scene.settings.threshold) break;
        const WallHit hit = exitWall(scene.room, s.origin, s.dir);
        pts.push_back(s.origin + s.dir * hit.t); // on the unfolded line == physical wall point
        reflect(scene.room, hit, s);
    }
    return pts;
}

} // namespace gart
